    {
        int a = Integer.parseInt(JOptionPane.showInputDialog(null, "Enter the min value"));
        int b = Integer.parseInt(JOptionPane.showInputDialog(null, "Enter the max value"));
        ImagePlus image = new ImagePlus();
        Opener opener= new Opener();
        image = opener.openImage(imp.getOriginalFileInfo().getFilePath());
        new ImageConverter(image).convertToGray8();
        ImageProcessor ip = image.getProcessor();
        int width = image.getWidth();
        int height = image.getHeight();
        for (int i = 0; i < width; i++)
        {
            for (int j = 0; j < height; j++)
            {
                if (ip.get(i,j) > 0 && ip.get(i,j) < a)
                {
                    int c  = b*ip.get(i,j)/a;
                    ip.set(i,j,c);
                }
                else if (ip.get(i,j) > a && ip.get(i,j) < 255)
                {
                    int c  = ((255-b)*ip.get(i,j) + 255*(b-a))/(255-a);
                    ip.set(i,j,c);
                }
            }
        }
        imp2 = image;
        im2 = image.getImage();
        ImageIcon image2 = new ImageIcon(im2);
        jLabel2 = new JLabel (new ImageIcon(image2.getImage()));
        jScrollPane2.setViewportView(jLabel2);
    }
    
