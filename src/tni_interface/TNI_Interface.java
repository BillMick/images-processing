    // RGB Function // A revoir //
    public void RGB() throws IOException
    {
        BufferedImage image = ImageIO.read(new File(imp.getOriginalFileInfo().getFilePath()));
        int width = image.getWidth();
        int height = image.getHeight();

        BufferedImage imageR = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        BufferedImage imageG = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        BufferedImage imageB = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);

        for (int i = 0; i < width; i++) {
            for (int j = 0; j < height; j++) {
                Color pixelColor = new Color(image.getRGB(i, j));

                int r = pixelColor.getRed();
                int g = pixelColor.getGreen();
                int b = pixelColor.getBlue();

                imageR.setRGB(i, j, new Color(r, 0, 0).getRGB());
                imageG.setRGB(i, j, new Color(0, g, 0).getRGB());
                imageB.setRGB(i, j, new Color(0, 0, b).getRGB());
            }
        }

        ImageIO.write(imageR, "png", new File("imageR.png"));
        ImageIO.write(imageG, "png", new File("imageG.png"));
        ImageIO.write(imageB, "png", new File("imageB.png"));

        System.out.println("Red, Green, and Blue channel images saved successfully!");
    }
    
